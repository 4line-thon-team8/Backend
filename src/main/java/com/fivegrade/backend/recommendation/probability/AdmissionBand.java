package com.fivegrade.backend.recommendation.probability;

/**
 * 학생 성적 대비 모집단위의 합격 가능성 구간.
 *
 * 확률 값은 "합격 확률"이 아니라 "최종 등록자 풀 안에 들어갈 가능성"에 대한 대리 지표이므로,
 * 사용자에게는 확률이 아니라 구간(가능성 구간)으로 보여 주는 것을 권장한다.
 */
public enum AdmissionBand {

	/** 안정: 풀 안에 들어갈 가능성이 높다. */
	SAFE,
	/** 적정: 풀 경계 근처다. */
	MATCH,
	/** 소신: 풀 바깥이지만 닿을 수 있는 거리다. */
	REACH,
	/** 먼 카드: 현실적으로 어렵다. */
	FAR,
	/** 과잉: 성적이 지나치게 높아 더 높은 곳을 노려도 되는 지원이다. */
	OVER,
	/** 평가 불가: 사용할 수 있는 컷이 전혀 없다. */
	UNRATED
}
